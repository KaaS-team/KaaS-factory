import { expect, test } from "bun:test";
import { mkdtempSync, mkdirSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const env = { ...process.env, GIT_CONFIG_GLOBAL: "/dev/null" };
const git = (cwd: string, ...a: string[]) =>
  Bun.spawnSync(["git", "-c", "user.name=t", "-c", "user.email=t@t", ...a], {
    cwd,
    env,
    stdout: "pipe",
    stderr: "pipe",
  });
const ident = {
  ...env,
  GIT_AUTHOR_NAME: "t",
  GIT_AUTHOR_EMAIL: "t@t",
  GIT_COMMITTER_NAME: "t",
  GIT_COMMITTER_EMAIL: "t@t",
};
const out = (p: ReturnType<typeof git>) => p.stdout.toString().trim();

function setup(file: string) {
  mkdirSync(tmpdir(), { recursive: true }); // the preload removes the root after each rerun
  const root = mkdtempSync(join(tmpdir(), "mw-"));
  const origin = join(root, "origin.git");
  const work = join(root, "work");
  git(root, "init", "-q", "--bare", "-b", "main", origin);
  git(root, "clone", "-q", origin, work);
  git(work, "checkout", "-q", "-b", "main");
  const put = (text: string) => {
    mkdirSync(join(work, file, ".."), { recursive: true });
    writeFileSync(join(work, file), text);
    git(work, "add", ".");
    git(work, "commit", "-q", "-m", text);
  };
  put("base\n");
  git(work, "push", "-q", "origin", "main");
  git(work, "checkout", "-q", "-b", "feat");
  put("branch\n");
  git(work, "push", "-q", "origin", "feat");
  git(work, "checkout", "-q", "main");
  put("main\n");
  git(work, "push", "-q", "origin", "main");
  return work;
}

const worker = (cwd: string) =>
  Bun.spawnSync(["bun", join(import.meta.dir, "../scripts/merge-worker.ts"), "feat"], {
    cwd,
    env: ident,
    stdout: "pipe",
    stderr: "pipe",
  });

test("a branch conflicting only in a regenerated file exits 0 with a merge commit", () => {
  // quality-baseline.json is regenerated by a repo script; give the temp repo a no-op one.
  const work = setup("quality-baseline.json");
  mkdirSync(join(work, "scripts"), { recursive: true });
  writeFileSync(join(work, "scripts/gen-quality-baseline.ts"), "");
  const r = worker(work);
  expect(r.exitCode).toBe(0);
  expect(r.stdout.toString()).toContain("ready");
  expect(out(git(work, "log", "-1", "--format=%p")).split(" ").length).toBe(2);
});

test("a conflict in src/a.ts exits 2, names it and leaves the tree clean", () => {
  const work = setup("src/a.ts");
  const r = worker(work);
  expect(r.exitCode).toBe(2);
  expect(r.stdout.toString()).toContain("src/a.ts");
  expect(out(git(work, "status", "--porcelain"))).toBe("");
});
