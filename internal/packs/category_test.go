package packs

import "testing"

func TestDetermineFileCategory(t *testing.T) {
	cases := []struct {
		name string
		file File
		want FileCategory
		low  bool
	}{
		{"binary skip wins", File{Name: "a_test.go", Skip: SkipBinary}, FileCategoryBinary, true},
		{"test", File{Name: "pkg/a_test.go"}, FileCategoryTest, true},
		{"dotfile", File{Name: ".eslintrc"}, FileCategoryDotFile, false},
		{"vendored", File{Name: "node_modules/x/index.js"}, FileCategoryVendored, true},
		{"generated by content", File{Name: "x.go", Content: []byte("// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n")}, FileCategoryGenerated, true},
		{"generated content ignored when too large", File{Name: "x.go", Content: []byte("// Code generated by protoc-gen-go. DO NOT EDIT.\n"), Skip: SkipTooLarge}, FileCategoryDefault, false},
		{"config", File{Name: "package.json"}, FileCategoryConfig, false},
		{"documentation", File{Name: "docs/guide.md"}, FileCategoryDocumentation, false},
		{"default", File{Name: "src/main.go", Content: []byte("package main\n")}, FileCategoryDefault, false},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got := DetermineFileCategory(c.file)
			if got != c.want {
				t.Fatalf("category = %d, want %d", got, c.want)
			}
			if got.LowPriority() != c.low {
				t.Fatalf("LowPriority = %v, want %v", got.LowPriority(), c.low)
			}
		})
	}
}
