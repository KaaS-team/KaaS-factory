// Kind says what a locked entry is.
type Kind string

// The kinds a lock entry may have.
const (
	KindSkill    Kind = "skill"
	KindAgent    Kind = "agent"
	KindWorkflow Kind = "workflow"
	KindCheck    Kind = "check"
)

// Valid reports whether k is one of the four kinds.
func (k Kind) Valid() bool {
	switch k {
	case KindSkill, KindAgent, KindWorkflow, KindCheck:
		return true
	}
	return false
}

// LockFile is the name of the lock file: a comment header, a version line, then one sorted JSON array per entry.
const LockFile = "factory.lock"

// Entry pins one fetched file. Ref carries the full sha it was fetched at.
type Entry struct {
	Kind      Kind     `json:"kind"`
	Ref       string   `json:"ref"`
	SHA       string   `json:"sha"`
	SHA256    string   `json:"sha256"`
	Licence   string   `json:"licence"`
	EvalScore *float64 `json:"eval_score,omitempty"`
}

// Lock is the parsed factory.lock.
type Lock struct {
	Entries []Entry
}

// NewLock returns an empty lock.
func NewLock() *Lock { return &Lock{} }

// Find returns the entry of the given kind for owner/repo#path, whatever its sha.
func (l *Lock) Find(kind Kind, r Ref) (Entry, bool) {
	for _, e := range l.Entries {
		er, err := ParseRef(e.Ref)
		if err == nil && e.Kind == kind && er.Slug() == r.Slug() && er.Path == r.Path {
			return e, true
		}
	}
	return Entry{}, false
}

// Put adds e, replacing an entry of the same kind, repo and path, and keeps the entries sorted.
func (l *Lock) Put(e Entry) error {
	nr, err := ParseRef(e.Ref)
	if err != nil {
		return err
	}
	if !e.Kind.Valid() {
		return fmt.Errorf("lock entry %s: unknown kind %q", e.Ref, e.Kind)
	}
	out := l.Entries[:0:0]
	for _, o := range l.Entries {
		or, err := ParseRef(o.Ref)
		if err == nil && o.Kind == e.Kind && or.Slug() == nr.Slug() && or.Path == nr.Path {
			continue
		}
		out = append(out, o)
	}
	out = append(out, e)
	sort.Slice(out, func(i, j int) bool {
		if out[i].Kind != out[j].Kind {
			return out[i].Kind < out[j].Kind
		}
		return out[i].Ref < out[j].Ref
	})
	l.Entries = out
	return nil
}

// ErrMergeConflict means the file holds unresolved git conflict markers.
var ErrMergeConflict = errors.New("factory.lock contains merge conflict markers; resolve them and run `factory packs verify`")

const versionLine = `[["version","2"]]`

// HeaderComment tops every written lock and tells readers, agents included, to commit it.
const HeaderComment = `# Generated by factory. Pins the upstream files this repo uses.
# Any factory packs command may update this file; always commit it with your changes.
# Do not edit by hand: re-run ` + "`factory packs add`" + ` instead.`

// Marshal returns the header, the version line and one sorted JSON array per entry.
func (l *Lock) Marshal() ([]byte, error) {
	es := append([]Entry(nil), l.Entries...)
	sort.Slice(es, func(i, j int) bool {
		if es[i].Kind != es[j].Kind {
			return es[i].Kind < es[j].Kind
		}
		return es[i].Ref < es[j].Ref
	})
	lines := []string{HeaderComment, versionLine}
	for _, e := range es {
		row := []any{e.Kind, e.Ref, e.SHA, e.SHA256, e.Licence}
		if e.EvalScore != nil {
			row = append(row, *e.EvalScore)
		}
		b, err := json.Marshal(row)
		if err != nil {
			return nil, err
		}
		lines = append(lines, string(b))
	}
	return []byte(strings.Join(lines, "\n") + "\n"), nil
}

func hasConflictMarkers(data []byte) bool {
	var start, sep, end bool
	for _, raw := range bytes.Split(data, []byte("\n")) {
		line := strings.TrimSpace(string(raw))
		start = start || strings.HasPrefix(line, "<<<<<<< ")
		sep = sep || line == "======="
		end = end || strings.HasPrefix(line, ">>>>>>> ")
	}
	return start && sep && end
}

// ParseLock reads a v2 lock, or the v1 JSON document older versions wrote, and checks every entry.
func ParseLock(b []byte) (*Lock, error) {
	if hasConflictMarkers(b) {
		return nil, ErrMergeConflict
	}
	var l *Lock
	var err error
	if t := bytes.TrimSpace(b); bytes.HasPrefix(t, []byte("{")) {
		l, err = parseV1(t)
	} else {
		l, err = parseV2(b)
	}
	if err != nil {
		return nil, err
	}
	for _, e := range l.Entries {
		r, err := ParseRef(e.Ref)
		if err != nil {
			return nil, err
		}
		if !e.Kind.Valid() || r.SHA == "" || e.SHA == "" || e.SHA256 == "" {
			return nil, fmt.Errorf("factory.lock: incomplete entry %s", e.Ref)
		}
	}
	return l, nil
}

type legacyLock struct {
	Version int `json:"version"`
	Entries []struct {
		Kind      Kind     `json:"kind"`
		Ref       string   `json:"ref"`
		SHA       string   `json:"sha"`
		SHA256    string   `json:"sha256"`
		Licence   string   `json:"licence"`
		EvalScore *float64 `json:"eval_score,omitempty"`
	} `json:"entries"`
}

func parseV1(b []byte) (*Lock, error) {
	var v legacyLock
	if err := json.Unmarshal(b, &v); err != nil {
		return nil, fmt.Errorf("factory.lock: %w", err)
	}
	if v.Version != 1 {
		return nil, fmt.Errorf("factory.lock: unsupported version %d", v.Version)
	}
	l := NewLock()
	for _, e := range v.Entries {
		l.Entries = append(l.Entries, Entry(e))
	}
	return l, nil
}

func parseV2(b []byte) (*Lock, error) {
	l := NewLock()
	seenVersion := false
	for i, raw := range strings.Split(string(b), "\n") {
		line := strings.TrimSpace(raw)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if !seenVersion {
			var h [][]string
			if err := json.Unmarshal([]byte(line), &h); err != nil || len(h) != 1 || len(h[0]) != 2 || h[0][0] != "version" {
				return nil, fmt.Errorf("factory.lock line %d: missing version header", i+1)
			}
			if h[0][1] != "2" {
				return nil, fmt.Errorf("factory.lock: unsupported version %q", h[0][1])
			}
			seenVersion = true
			continue
		}
		var row []json.RawMessage
		if err := json.Unmarshal([]byte(line), &row); err != nil || (len(row) != 5 && len(row) != 6) {
			return nil, fmt.Errorf("factory.lock line %d: want 5 or 6 fields", i+1)
		}
		var e Entry
		strs := []any{&e.Kind, &e.Ref, &e.SHA, &e.SHA256, &e.Licence}
		for j, p := range strs {
			if err := json.Unmarshal(row[j], p); err != nil {
				return nil, fmt.Errorf("factory.lock line %d: field %d: %w", i+1, j+1, err)
			}
		}
		if len(row) == 6 {
			e.EvalScore = new(float64)
			if err := json.Unmarshal(row[5], e.EvalScore); err != nil {
				return nil, fmt.Errorf("factory.lock line %d: eval score: %w", i+1, err)
			}
		}
		l.Entries = append(l.Entries, e)
	}
	return l, nil
}

// ReadLock reads path, and returns an empty lock when the file does not exist.
func ReadLock(path string) (*Lock, error) {
	b, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return NewLock(), nil
	}
	if err != nil {
		return nil, err
	}
	return ParseLock(b)
}

// WriteLock writes the lock to path.
func WriteLock(path string, l *Lock) error {
	b, err := l.Marshal()
	if err != nil {
		return err
	}
	return os.WriteFile(path, b, 0o644)
}
